// Run: NODE_PATH=$(npm root -g) node scripts/tests/staff-certificates.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const read = name => fs.readFileSync(name, 'utf8');
const model = read('apps/web/src/lib/staff-certificate.ts');
const code = ts.transpileModule(model, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {}, Date, Intl, Math, Number, String };
vm.runInNewContext(code, context);
const { certificateDaysRemaining: days, certificateExpiryState: state } = context.exports;
assert.equal(days(null,'2026-11-02'), null);
assert.equal(days('2026-11-02','2026-11-02'), 0);
assert.equal(days('2026-11-12','2026-11-02'), 10);
assert.equal(days('2026-10-31','2026-11-02'), -2);
assert.equal(state(null,30,'2026-11-02'), 'none');
assert.equal(state('2026-11-12',7,'2026-11-02'), 'valid');
assert.equal(state('2026-11-12',30,'2026-11-02'), 'due');
assert.equal(state('2026-11-12',0,'2026-11-02'), 'valid');
assert.equal(state('2026-11-02',0,'2026-11-02'), 'due');
assert.equal(state('2026-10-31',0,'2026-11-02'), 'expired');
const sql = read('infra/sql/063_staff_certificates.sql');
for(const field of ['tenant_id','membership_id','title','category','issuing_organisation','certificate_number','issued_date','expiry_date','reminder_days','notes','file_path','file_name']) assert(sql.includes(field));
assert(sql.includes('public = false'));
assert(sql.includes('ON DELETE CASCADE'));
const server = read('apps/web/src/server/staff-certificates.ts');
const action = read('apps/web/src/app/(app)/users/[membershipId]/certificates/actions.ts');
const signer = read('apps/web/src/app/api/staff-certificates/upload-sign/route.ts');
const file = read('apps/web/src/app/api/staff-certificates/file/[certificateId]/route.ts');
const alerts = read('apps/web/src/server/notifications.ts');
const api = read('apps/web/src/app/api/notifications/route.ts');
assert(server.includes('ON CONFLICT DO NOTHING'), 'events deduplicated across app instances');
assert(server.includes('WHERE c.tenant_id=$1::uuid'), 'alerts tenant scoped');
assert(server.includes("m.status='active'"));
assert(server.includes("AT TIME ZONE 'Australia/Sydney'"));
assert(server.includes("stage IN ('due', 'expired')") || sql.includes("stage IN ('due', 'expired')"));
assert(server.includes('UPDATE app.notifications SET is_read=true'), 'obsolete alerts marked read after editing');
assert(action.includes('canManageStaff') && action.includes('tenant.membershipStatus !== "active"'));
assert(signer.includes('staffMemberInTenant') && signer.includes('canManageStaff'));
assert(file.includes('canManageStaff') && file.includes('getStaffCertificate(tenant.tenantId, certificateId)'));
assert(file.includes('createSignedUrl') && !file.includes('getPublicUrl'));
assert(api.includes('canManageStaff(activeTenant.tenantRole)'));
assert(alerts.includes("event_type <> 'staff_certificate_expiry'"), 'staff cannot view manager alerts');
assert(alerts.includes('5 * 60 * 1000'), 'do not scan every 60s refresh');
assert(read('apps/web/src/app/(app)/users/page.tsx').includes('Manage training / certificates'));
console.log('PASS: expiry/date logic; tenant/role access; private evidence; alert deduplication; scan throttling; UI navigation');
