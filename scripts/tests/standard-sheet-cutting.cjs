const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const compile = (src) => {
  const output = {};
  new Function('exports', ts.transpileModule(src, {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText)(output);
  return output;
};
const { standardSheetCuttingMinutesPerSheet, allocatedStandardSheetCutting } = compile(read('apps/web/src/lib/standard-sheet-cutting.ts'));
assert.equal(standardSheetCuttingMinutesPerSheet('corflute',null),5);
assert.equal(standardSheetCuttingMinutesPerSheet('acm',undefined),5);
assert.equal(standardSheetCuttingMinutesPerSheet('pvc',null),0);
assert.equal(standardSheetCuttingMinutesPerSheet('corflute','0'),0);
assert.equal(standardSheetCuttingMinutesPerSheet('acm','8.5'),8.5);
assert.equal(standardSheetCuttingMinutesPerSheet('acm',''),5);
assert.equal(standardSheetCuttingMinutesPerSheet('acm','bad'),5);
const base = {baseType:'corflute', configuredMinutesPerSheet:null, calculatedSheetUse:1, finishedQuantity:4, specialtyCutSelected:false};
assert.deepEqual(allocatedStandardSheetCutting(base),{minutesPerSheet:5,minutesPerItem:1.25,totalMinutes:5});
assert.deepEqual(allocatedStandardSheetCutting({...base,baseType:'acm'}),{minutesPerSheet:5,minutesPerItem:1.25,totalMinutes:5});
assert.equal(allocatedStandardSheetCutting({...base,calculatedSheetUse:0.25,finishedQuantity:1}).minutesPerItem,1.25);
assert.equal(allocatedStandardSheetCutting({...base,calculatedSheetUse:2.5,finishedQuantity:10}).minutesPerItem,1.25);
assert.equal(allocatedStandardSheetCutting({...base,configuredMinutesPerSheet:'0'}).totalMinutes,0);
assert.equal(allocatedStandardSheetCutting({...base,configuredMinutesPerSheet:'10'}).minutesPerItem,2.5);
assert.equal(allocatedStandardSheetCutting({...base,specialtyCutSelected:true}).totalMinutes,0);
assert.equal(allocatedStandardSheetCutting({...base,calculatedSheetUse:0}).totalMinutes,0);
const builder = read('apps/web/src/app/(app)/quotes/QuoteMaterialFlowBuilder.tsx');
assert.match(builder,/allocatedStandardSheetCutting\(\{/);
assert.match(builder,/calculatedSheetUse: sheetUse.calculatedTotal/);
assert.match(builder,/specialtyCutSelected: finishings.includes\("jingwei"\)/);
assert.match(builder,/label: "Standard sheet cutting"/);
assert.match(builder,/standardCut.minutesPerItem \* labourRatePerMinute/);
assert.match(builder,/standardCutMinutesPerSheet: material.standardCutMinutesPerSheet \?\? null/);
const materialServer = read('apps/web/src/server/materials.ts');
assert.match(materialServer,/m.cost_json ->> 'standardCutMinutesPerSheet'/);
for (const param of [26,27,32,33]) assert.match(materialServer,new RegExp(`'standardCutMinutesPerSheet',\\$${param}::numeric`));
assert.match(read('apps/web/src/app/(app)/materials/MaterialPriceManager.tsx'),/"Cut min\/sheet"/);
assert.match(read('apps/web/src/app/(app)/materials/MaterialForms.tsx'),/name="standardCutMinutesPerSheet"/);
assert.match(read('apps/web/src/app/(app)/quotes/quoteLineSnapshot.ts'),/standardCutMinutesPerSheet: stringValue\(value.standardCutMinutesPerSheet\)/);
console.log('PASS Corflute + ACM per-sheet cutting default, yield allocation, overrides, specialty replacement, material persistence, cost snapshot');
